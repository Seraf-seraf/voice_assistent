// Package llm определяет независимый от транспорта порт потоковой генерации текста.
//
// Generator.Generate блокируется до завершения генерации. Возвращённая ошибка
// или nil — единственный итоговый результат. Функция emit обязательна и
// вызывается последовательно в порядке текста, без конкурентных вызовов.
// После возврата Generate не должен выдавать новые фрагменты или продолжать
// работу. Каждый TextDelta.Text — добавочный фрагмент, а не накопленный текст и
// не обязательно один токен. Фрагменты содержат корректный UTF-8 без маркеров
// модели и внутренних рассуждений; декодирование неполных UTF-8 байтов относится
// к адаптеру. Пустые фрагменты ничего не добавляют. Пробелы и границы слов
// сохраняются точно. Если emit возвращает ошибку, генерация останавливается,
// а Generate возвращает ошибку с сохранённой причиной; игнорировать её и
// вернуть nil — нарушение контракта. Переданный context действует на протяжении
// генерации; при обнаруженной отмене вызов завершается ошибкой, соответствующей
// context.Canceled или context.DeadlineExceeded.
//
// Request и снимок Dialogue предоставляются во временное пользование на время
// Generate: генератор не должен изменять их или сохранять после возврата.
// Конкурентные вызовы одного Generator не входят в контракт; один владелец
// вызывает его последовательно. Options проверяются до выдачи текста. MaxTokens
// ограничивает число новых токенов модели, а не символы или общий размер запроса.
