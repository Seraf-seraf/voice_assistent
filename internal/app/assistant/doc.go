// Package assistant содержит прикладную среду выполнения для обработки событий речи.
//
// Transcriber последовательно распознаёт завершённые реплики вне цикла обработки
// событий. InputProcessor нормализует результат распознавания и направляет
// команды и запросы. Responder — единственная граница жизненного цикла создания
// и завершения ответа через llm.Generator: во время генерации он передаёт
// текстовые дельты в ResponseSink, а полный ответ сохраняет в Dialogue только
// после успешного завершения вывода. В рабочей сборке Responder последовательно
// вызывается рабочей горутиной STT. Текстовые дельты выдаются потоково; речевой вывод
// выполняется отдельным приёмником. Подтверждённое SpeechStarted создаёт новое
// поколение входа: Transcriber быстро отменяет только активное задание и удаляет
// ожидающие задания прежнего поколения. SpeechEnded без нового начала речи
// сохраняют FIFO и ограниченную ёмкость очереди; переполнение возвращает ошибку.
// Один worker остаётся единственным владельцем STT, Responder и Dialogue.Manager.
// Он ждёт завершения старого handler и очистки речевого worker до нового задания.
//
// ResponseSink получает для одного хода от нуля до нескольких последовательных
// Push, за которыми следует Complete либо Abort. Успешный Complete завершает
// жизненный цикл вывода; если Complete возвращает ошибку, Responder вызывает
// Abort для очистки незавершённого вывода.
// ResponseDelta.Text — добавочный фрагмент; Responder не передаёт пустые
// дельты, а конкатенация принятых Push.Text совпадает с Response.Text в
// Complete. Обычный текстовый приёмник подтверждает доставку текста. Речевой приёмник
// подтверждает Complete только после синтеза принятых фраз и подтверждения
// завершения воспроизведения адаптером. При Abort он возвращает ID хода и raw-префикс
// фраз, для которых Player.Play успешно завершился; это подтверждение backend drain,
// а не точное доказательство физически услышанных слов. Responder записывает только
// этот непрерывный префикс при пользовательском прерывании. Текстовый вывод не
// считается воспроизведённым и остаётся только на экране. Успешный Complete остаётся
// границей принятия полного ответа. Такой приёмник может владеть одной рабочей
// горутиной и дочерним контекстом своей сессии, но не владеет родительским
// контекстом, Dialogue.Manager или Generator. Рабочая горутина не читает историю
// диалога и не записывает запрос, ответ или PCM в журнал приложения. Abort
// отменяет рабочую горутину, дожидается безопасного завершения текущего нативного
// вызова, если он уже начался, и не синтезирует оставшийся текст или не ждёт
// завершения отменённого воспроизведения. Вычисление нативной модели не обещает
// мгновенную отмену. Методы sink и Dialogue не вызываются из audio worker или
// обработчика SpeechStarted. После успешного завершающего вызова для хода новых
// вызовов нет.
//
// Все методы приёмника вызываются последовательно одним владельцем; конкурентные
// вызовы не поддерживаются. Отмена контекста запроса не мешает Responder вызвать
// Abort с context.WithoutCancel для локальной очистки.
